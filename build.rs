//! Compiles the committed, generated Tree-sitter parser into the build.
//!
//! `tree-sitter-k65/src/parser.c` is generated by a maintainer (see
//! `tree-sitter-k65/grammar.js`) and committed; a clean checkout builds
//! without Node.js or the Tree-sitter CLI. `src/scanner.c` is written by
//! hand: the one token the grammar cannot express, a line break after a raw
//! mnemonic.

fn main() {
    let src = std::path::Path::new("tree-sitter-k65/src");
    println!("cargo:rerun-if-changed=tree-sitter-k65/src/parser.c");
    println!("cargo:rerun-if-changed=tree-sitter-k65/src/scanner.c");
    println!("cargo:rerun-if-changed=tree-sitter-k65/src/tree_sitter/parser.h");
    cc::Build::new()
        .include(src)
        .file(src.join("parser.c"))
        .file(src.join("scanner.c"))
        .warnings(false)
        .compile("tree-sitter-k65");
}
