//! The evaluator subset `for … eval` needs: integer arithmetic over a loop
//! variable and the constants already in scope.
//!
//! Sub-plan E's decision 18 is what this module is: data generated by
//! iteration is a compile-time loop over an integer range whose body folds to
//! values, and *only* that. The rest of K65's evaluator — floating point, the
//! function library, assignment, section mutation, the side-effecting calls —
//! belongs to sub-plan G, which owns the compatibility surface. What does not
//! fold here is [`Unsupported`], and every variant of it names who owns the
//! form rather than pretending it is a syntax error.
//!
//! The line is drawn at *floating point* rather than at determinism, and the
//! reason is worth stating because `sin` is perfectly deterministic. K65's
//! reference says an evaluator value is converted to a byte "by rounding to
//! nearest integer and `AND`-ing with `0xFF`"; K816's says integer contexts
//! "require an exact integer value" and that the compiler "does not round
//! evaluator values or mask them to one byte automatically". Those are two
//! different numeric models, and picking one is the evaluator owner's call —
//! not a decision to make in passing while implementing data blocks.

use crate::ast::{EvalExpr, EvalExprKind};
use crate::source::Span;
use crate::symbol::{SymbolKind, SymbolTable};

/// A form the deterministic subset does not fold, and where it appeared.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Unsupported {
    /// A floating-point literal, or a call that would produce one.
    Numeric { span: Span, what: String },
    /// A form that is evaluator syntax rather than arithmetic: assignment,
    /// subscripting, member access, a string.
    Form { span: Span, what: &'static str },
    /// An identifier that is neither the loop variable nor a `const`.
    Name { span: Span, name: String },
    /// Arithmetic that has no answer: division or remainder by zero.
    Undefined { span: Span, what: &'static str },
    /// A construct that has *already* reported itself, so the caller has
    /// nothing to add.
    ///
    /// The reserved evaluator calls are the case: `rnd()` in a `for … eval`
    /// body is `K816-K65-0002`, which analysis reports when it walks the
    /// expression, and sub-plan E's decision 18 says that is the diagnostic
    /// such a body keeps. Folding it fails too, of course — but a second
    /// complaint about one call is one complaint too many.
    Reported,
}

/// What the body of one `for … eval` iteration is evaluated against.
pub struct Bindings<'a> {
    /// The loop variable's name and its value for this iteration.
    pub variable: (&'a str, i64),
    /// The unit's symbols, for the `const` names a body may use.
    pub symbols: &'a SymbolTable,
}

impl Bindings<'_> {
    fn lookup(&self, name: &str) -> Option<i64> {
        if name == self.variable.0 {
            return Some(self.variable.1);
        }
        let id = self.symbols.lookup(name)?;
        match self.symbols.kind(id) {
            SymbolKind::Const { value } => Some(i64::from(value)),
            _ => None,
        }
    }
}

/// Folds one evaluator expression to an integer.
///
/// Arithmetic is done in `i64` so that intermediate values may go negative
/// and wide without wrapping into a different answer; whether the *result*
/// fits what it is being emitted into is the caller's question, because only
/// the caller knows the width.
pub fn fold(expr: &EvalExpr, bindings: &Bindings<'_>) -> Result<i64, Unsupported> {
    match &expr.kind {
        EvalExprKind::Number(value) => Ok(i64::from(*value)),
        EvalExprKind::Symbol(name) => bindings.lookup(&name.text).ok_or(Unsupported::Name {
            span: name.span,
            name: name.text.clone(),
        }),
        EvalExprKind::Unary {
            operator,
            operand,
            is_suffix,
        } => {
            // `x++` mutates, and mutation is state this subset does not have.
            if *is_suffix || operator == "++" || operator == "--" {
                return Err(Unsupported::Form {
                    span: expr.span,
                    what: "increment and decrement",
                });
            }
            let value = fold(operand, bindings)?;
            match operator.as_str() {
                "+" => Ok(value),
                "-" => Ok(-value),
                "~" => Ok(!value),
                "!" => Ok(i64::from(value == 0)),
                _ => Err(Unsupported::Form {
                    span: expr.span,
                    what: "this operator",
                }),
            }
        }
        EvalExprKind::Binary {
            operator,
            left,
            right,
        } => {
            let (a, b) = (fold(left, bindings)?, fold(right, bindings)?);
            let logical = |value: bool| Ok(i64::from(value));
            match operator.as_str() {
                "+" => Ok(a.wrapping_add(b)),
                "-" => Ok(a.wrapping_sub(b)),
                "*" => Ok(a.wrapping_mul(b)),
                "/" | "%" if b == 0 => Err(Unsupported::Undefined {
                    span: expr.span,
                    what: if operator == "/" {
                        "division by zero"
                    } else {
                        "a remainder by zero"
                    },
                }),
                "/" => Ok(a.wrapping_div(b)),
                "%" => Ok(a.wrapping_rem(b)),
                "<<" => Ok(a.wrapping_shl(u32::try_from(b).unwrap_or(u32::MAX))),
                ">>" => Ok(a.wrapping_shr(u32::try_from(b).unwrap_or(u32::MAX))),
                "&" => Ok(a & b),
                "|" => Ok(a | b),
                "^" => Ok(a ^ b),
                // `?>` and `?<` select the greater and the smaller value —
                // K65's minimum and maximum, spelled as operators.
                "?>" => Ok(a.max(b)),
                "?<" => Ok(a.min(b)),
                "<" => logical(a < b),
                "<=" => logical(a <= b),
                ">" => logical(a > b),
                ">=" => logical(a >= b),
                "==" => logical(a == b),
                "!=" => logical(a != b),
                "&&" => logical(a != 0 && b != 0),
                "||" => logical(a != 0 || b != 0),
                _ => Err(Unsupported::Form {
                    span: expr.span,
                    what: "this operator",
                }),
            }
        }
        EvalExprKind::Ternary {
            condition,
            consequence,
            alternative,
        } => {
            // Both arms fold, so a body that is wrong in the branch this
            // iteration did not take is still reported — the loop would
            // otherwise refuse on iteration 7 and not on iteration 6.
            let taken = fold(condition, bindings)? != 0;
            let consequence = fold(consequence, bindings);
            let alternative = fold(alternative, bindings);
            if taken { consequence } else { alternative }
        }
        // A list's value is its last item, and the ones before it are only
        // useful for their side effects — which this subset does not have.
        EvalExprKind::List(items) => match items.last() {
            Some(last) if items.len() == 1 => fold(last, bindings),
            _ => Err(Unsupported::Form {
                span: expr.span,
                what: "an expression list",
            }),
        },
        EvalExprKind::Float(text) => Err(Unsupported::Numeric {
            span: expr.span,
            what: format!("the floating-point literal `{text}`"),
        }),
        EvalExprKind::Call { name, .. } => Err(Unsupported::Numeric {
            span: expr.span,
            what: format!("a call to `{}`", name.text),
        }),
        EvalExprKind::String(_) => Err(Unsupported::Form {
            span: expr.span,
            what: "a string",
        }),
        EvalExprKind::Assignment { .. } => Err(Unsupported::Form {
            span: expr.span,
            what: "assignment",
        }),
        EvalExprKind::Subscript { .. } => Err(Unsupported::Form {
            span: expr.span,
            what: "subscripting",
        }),
        EvalExprKind::Member { .. } => Err(Unsupported::Form {
            span: expr.span,
            what: "member access",
        }),
        // A reserved call reports itself through `K816-K65-0002`, and an
        // error node reported itself as a syntax error; both are already
        // said, so neither is said again.
        EvalExprKind::ReservedCall(_) | EvalExprKind::Error => Err(Unsupported::Reported),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::parse_source;
    use crate::source::SourceMap;

    /// Folds `body` with `x` bound to `value`, through a real parse.
    fn eval(body: &str, value: i64) -> Result<i64, Unsupported> {
        let source = format!("const K = 10\ndata d {{\n  for x=0..1 eval [ {body} ]\n}}\n");
        let mut map = SourceMap::new();
        let id = map.add_file("eval.k65", &source);
        let parsed = parse_source(map.file(id), None);
        assert_eq!(parsed.diagnostics, vec![], "`{body}` did not parse");
        // Analysis is run only for its symbol table: whether the body folds
        // is exactly what these tests are asking, so its diagnostics are the
        // question rather than a precondition.
        let (model, _) = crate::semantic::analyze_file(&parsed.file);

        let crate::ast::ItemKind::Data(block) = &parsed.file.items[1].kind else {
            panic!("expected a data block");
        };
        let crate::ast::DataEntryKind::ForEval { body, .. } = &block.entries[0].kind else {
            panic!("expected a `for … eval` entry");
        };
        let crate::ast::ExprKind::Eval(body) = &body.kind else {
            panic!("the body is an evaluator bracket");
        };
        fold(
            body,
            &Bindings {
                variable: ("x", value),
                symbols: &model.symbols,
            },
        )
    }

    #[test]
    fn arithmetic_folds_over_the_loop_variable_and_constants() {
        assert_eq!(eval("x", 7), Ok(7));
        assert_eq!(eval("x * K", 7), Ok(70));
        assert_eq!(eval("x + 1 * 2", 7), Ok(9), "precedence is the grammar's");
        assert_eq!(eval("(x + 1) * 2", 7), Ok(16));
        assert_eq!(eval("-x", 7), Ok(-7), "intermediates may go negative");
        assert_eq!(eval("255 - x", 7), Ok(248));
        assert_eq!(eval("x % 3", 7), Ok(1));
        assert_eq!(eval("x << 4", 7), Ok(112));
        assert_eq!(eval("x & 3 | 8", 7), Ok(11));
        assert_eq!(eval("~x & 255", 7), Ok(248));
    }

    #[test]
    fn comparison_and_selection_answer_in_integers() {
        assert_eq!(eval("x > 5", 7), Ok(1));
        assert_eq!(eval("x > 5", 3), Ok(0));
        assert_eq!(eval("x ?> 5", 3), Ok(5), "`?>` selects the greater");
        assert_eq!(eval("x ?< 5", 7), Ok(5), "`?<` selects the smaller");
        assert_eq!(eval("x > 5 ? 100 : 200", 7), Ok(100));
        assert_eq!(eval("x > 5 ? 100 : 200", 3), Ok(200));
        assert_eq!(eval("!x", 0), Ok(1));
    }

    #[test]
    fn what_is_not_in_the_subset_says_so_precisely() {
        assert!(matches!(eval("1.5", 0), Err(Unsupported::Numeric { .. })));
        assert!(matches!(
            eval("sin(x)", 0),
            Err(Unsupported::Numeric { .. })
        ));
        assert!(matches!(eval("x = 1", 0), Err(Unsupported::Form { .. })));
        assert!(matches!(eval("x++", 0), Err(Unsupported::Form { .. })));
        assert!(matches!(eval("nope", 0), Err(Unsupported::Name { .. })));
        assert!(matches!(
            eval("x / 0", 0),
            Err(Unsupported::Undefined { .. })
        ));
        // A reserved call has already been reported as reserved legacy
        // syntax, so folding it adds nothing (sub-plan E, decision 18).
        assert_eq!(eval("rnd() & 255", 0), Err(Unsupported::Reported));
    }
}
